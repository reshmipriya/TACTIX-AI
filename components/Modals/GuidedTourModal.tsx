import { useEffect, useState } from "react";
import { useViewMode } from "@/lib/context/ViewModeContext";
import { 
  Check, 
  ArrowRight, 
  ArrowLeft, 
  Sparkles, 
  Compass, 
  RotateCcw, 
  Zap, 
  Package, 
  Leaf 
} from "lucide-react";

